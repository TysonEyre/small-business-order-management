-- Run on an empty PostgreSQL database.
-- Tables are created in foreign-key dependency order.

CREATE TABLE customers (
    CustomerID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CustomerName VARCHAR(50) NOT NULL,
    CustomerEmail VARCHAR(50) NOT NULL UNIQUE,
    CustomerPhone VARCHAR(50),
    CurrentAddress VARCHAR(100)
);

CREATE TABLE products (
    ProductID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ProductName VARCHAR(100) NOT NULL,
    CurrentPrice DECIMAL(10,2) NOT NULL CHECK (CurrentPrice >= 0),
    SKU VARCHAR(20) NOT NULL UNIQUE,
    IsActive BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sales_reps (
    SalesRepID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    SalesRepName VARCHAR(100) NOT NULL
);

CREATE TABLE order_statuses (
    StatusID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    StatusName VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE orders (
    OrderID INT GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    CustomerID INT NOT NULL REFERENCES customers(CustomerID) ON DELETE RESTRICT,
    SalesRepID INT NOT NULL REFERENCES sales_reps(SalesRepID) ON DELETE RESTRICT,
    OrderStatusID INT NOT NULL REFERENCES order_statuses(StatusID) ON DELETE RESTRICT,
    OrderDate TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ShippingAddress VARCHAR(100)
);

CREATE TABLE order_items (
    OrderItemID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    OrderID INT NOT NULL REFERENCES orders(OrderID) ON DELETE CASCADE,
    ProductID INT NOT NULL REFERENCES products(ProductID) ON DELETE RESTRICT,
    Quantity INT NOT NULL CHECK (Quantity > 0),
    UnitPrice DECIMAL(10,2) NOT NULL CHECK (UnitPrice >= 0)
);

CREATE TABLE order_status_history (
    OrderStatusHistoryID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    OrderID INT NOT NULL REFERENCES orders(OrderID) ON DELETE RESTRICT,
    StatusID INT NOT NULL REFERENCES order_statuses(StatusID) ON DELETE RESTRICT,
    ChangedAt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
